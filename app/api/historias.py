IMPLEMENTADAS = {"HU-001", "HU-002", "HU-005", "HU-007", "HU-034", "HU-037", "HU-038", "HU-043", "HU-044", "HU-054"}

_por_id = {h["hu"]: h for h in HISTORIAS}


def tag(hu: str) -> str:
    """Nombre de la etiqueta de Swagger para una historia, por ejemplo 'HU-001 · Gestionar las sucursales de la cadena'."""
    return f"{hu} · {_por_id[hu]['titulo']}"


def tags_openapi() -> list[dict]:
    salida = [{"name": "Sistema", "description": "Estado del servicio (health check)."}]
    for h in HISTORIAS:
        estado = "✅ Implementada" if h["hu"] in IMPLEMENTADAS else "🕓 Planificada"
        salida.append({
            "name": tag(h["hu"]),
            "description": f"{estado} · API {h['tipo'].lower()} · Prioridad {h['prioridad']} · {h['sprint']}",
        })
    return salida
